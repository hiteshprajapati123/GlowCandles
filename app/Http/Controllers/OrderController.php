    /**
     * Display a listing of the user's orders.
     */
    public function index()
    {
        $user = Auth::user();
        $orders = $user->orders()
            ->with(['items' => function($query) {
                $query->with('product');
            }])
            ->latest()
            ->paginate(10);
        
        return view('orders.index', [
            'orders' => $orders,
            'user' => $user
        ]);
    }

